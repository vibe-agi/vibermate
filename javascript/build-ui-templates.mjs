import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const output = resolve(
  root,
  '../ui/flutter_app/lib/features/workbench/built_in_script_templates.g.dart',
);
const inputs = {
  localRequest: await readFile(resolve(root, 'hide-local-identity/request.js'), 'utf8'),
  localResponse: await readFile(resolve(root, 'hide-local-identity/response.js'), 'utf8'),
  metadataRequest: await readFile(resolve(root, 'hide-client-metadata/request.js'), 'utf8'),
};

for (const [name, source] of Object.entries(inputs)) {
  if (!source.endsWith('\n') || source.includes("'''")) {
    throw new Error(name + ' cannot be represented as one exact Dart raw string');
  }
}

const localVersion = /ViberMate local identity (v\d+)/.exec(inputs.localRequest)?.[1];
const metadataVersion = /客户端元信息替换 (v\d+)/.exec(inputs.metadataRequest)?.[1];
if (localVersion == null || metadataVersion == null ||
    !inputs.localResponse.includes('ViberMate local identity ' + localVersion)) {
  throw new Error('template version markers are missing or inconsistent');
}

const digest = value => createHash('sha256').update(value).digest('hex');
const raw = value => "r'''" + value + "'''";
const generated = `// Generated by javascript/build-ui-templates.mjs. Do not edit.
// The JavaScript files under javascript/ are the single source of truth.

const builtInHideLocalIdentityVersion = '${localVersion}';
const builtInHideLocalIdentityDigest =
    '${digest(inputs.localRequest + '\0' + inputs.localResponse)}';
const builtInHideLocalIdentityRequest =
    ${raw(inputs.localRequest)};
const builtInHideLocalIdentityResponse =
    ${raw(inputs.localResponse)};

const builtInHideClientMetadataVersion = '${metadataVersion}';
const builtInHideClientMetadataDigest =
    '${digest(inputs.metadataRequest)}';
const builtInHideClientMetadataRequest =
    ${raw(inputs.metadataRequest)};
`;

let current = '';
try {
  current = await readFile(output, 'utf8');
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}
if (process.argv.includes('--check')) {
  if (current !== generated) {
    throw new Error('Flutter JavaScript template projection is stale; run node javascript/build-ui-templates.mjs');
  }
} else if (current !== generated) {
  await writeFile(output, generated, { mode: 0o644 });
}
