// Generated by the Runtime's own handler
// (internal/desktopcontrol/native_tool_approvals_all_test.go), so it reads a
// file and runs on the VM only.
Map<String, Object?> sample() =>
    jsonDecode(
          File('../../api/samples/native-approvals.json').readAsStringSync(),
        )
        as Map<String, Object?>;

List<Map<String, Object?>> sampleItems() => [
  for (final item in sample()['items']! as List<Object?>)
    item! as Map<String, Object?>,
];

const allSessionsPath = '/api/v1/native-tools/approvals';

http.Response json(Object? body, {int status = 200}) => http.Response(
  jsonEncode(body),
  status,
  headers: {'content-type': 'application/json', 'cache-control': 'no-store'},
);

void main() {
  test('the list across sessions the Runtime sends can be read', () {
    final page = NativeSessionApprovalPage.fromJson(
      sample(),
      cursor: '',
      limit: 50,
    );
    expect(page.nextCursor, isEmpty);
    expect(page.items.map((item) => item.approval.captureKey), [
      'managed_run:same-id',
      'manual_capture:same-id',
    ]);
    expect(page.items.map((item) => item.captureDisplayName), [
      'claude',
      'Manual app',
    ]);
    expect(page.items.first.approval.canAllow, isTrue);
    expect(page.items.first.approval.intents.single.toolName, 'read_file');
    expect(page.items.last.approval.canAllow, isFalse);
    expect(page.items.last.approval.pending, isTrue);
  });

  test('the list across sessions keeps the strict approval contract', () {
    final valid = sampleItems();
    Map<String, Object?> page(List<Object?> items) => {
      'items': items,
      'nextCursor': '',
    };
    Map<String, Object?> withApproval(
      Map<String, Object?> item,
      Map<String, Object?> change,
    ) => {
      ...item,
      'approval': {...item['approval']! as Map<String, Object?>, ...change},
    };
    for (final bad in <Map<String, Object?>>[
      page([
        {...valid.first, 'sessionKey': 'extra'},
      ]),
      page([
        {...valid.first}..remove('captureDisplayName'),
      ]),
      page([
        {...valid.first, 'captureDisplayName': ''},
      ]),
      page([
        {...valid.first, 'captureDisplayName': ' claude'},
      ]),
      page([
        {...valid.first, 'captureDisplayName': 'claude\n'},
      ]),
      page([
        withApproval(valid.first, {'captureKey': 'legacy-capture'}),
      ]),
      page([
        withApproval(valid.first, {'credentialOwner': 'managed_account'}),
      ]),
      page([
        withApproval(valid.first, {'state': 'allowed'}),
      ]),
      page([
        withApproval(valid.first, {'unexpected': true}),
      ]),
      // One session cannot carry two names on one page.
      page([
        valid.first,
        withApproval(
          {...valid.last, 'captureDisplayName': 'renamed'},
          {'captureKey': 'managed_run:same-id'},
        ),
      ]),
      page([valid.first, valid.first]),
      {...page(valid), 'nextCursor': 'not a cursor'},
    ]) {
      expect(
        () => NativeSessionApprovalPage.fromJson(bad, cursor: '', limit: 50),
        throwsA(isA<ControlContractException>()),
        reason: jsonEncode(bad),
      );
    }
    expect(
      () =>
          NativeSessionApprovalPage.fromJson(page(valid), cursor: '', limit: 1),
      throwsA(isA<ControlContractException>()),
    );
  });

  testWidgets(
    'Waiting lists two sessions’ tool questions, counts both, and decides each in its own session',
    (tester) async {
      final items = sampleItems();
      final approvals = {
        for (final item in items)
          (item['approval']! as Map<String, Object?>)['id']! as String:
              item['approval']! as Map<String, Object?>,
      };
      final decided = <String>{};
      final posts = <http.Request>[];
      final client = MockClient((request) async {
        final path = Uri.decodeComponent(request.url.path);
        if (path == allSessionsPath) {
          return json({
            'items': [
              for (final item in items)
                if (!decided.contains(
                  (item['approval']! as Map<String, Object?>)['id'],
                ))
                  item,
            ],
            'nextCursor': '',
          });
        }
        final id = path.split('/').where((part) => part.length == 32).last;
        final approval = approvals[id]!;
        if (request.method == 'POST') {
          posts.add(request);
          decided.add(id);
          return json(
            {
              ...approval,
              'state': 'denied',
              'revision': 2,
              'previewState': 'unavailable',
            }..remove('preview'),
          );
        }
        return json(approval);
      });
      final api = await HttpControlApi.connect(
        DesktopSession(
          baseUrl: Uri.parse('http://127.0.0.1:43129'),
          readToken: 'R' * 43,
          writeToken: 'W' * 43,
          instanceId: 'synthetic',
          expiresAt: DateTime.now().toUtc().add(const Duration(hours: 1)),
        ),
        inspectSession: false,
        client: client,
      );
      addTearDown(api.close);
      final fixture = PreviewControlApi();
      final controller = WorkbenchController(
        api: api,
        terminalCommands: PreviewTerminalCommandService(),
        previewMode: true,
        closeRuntime: fixture.close,
      );
      addTearDown(controller.dispose);
      // Only the managed run is selected; the manual session's question
      // still shows and is answered where it waits.
      controller.selectedCaptureKey = 'managed_run:same-id';
      controller.pendingApprovals = const [];
      final network = (await tester.runAsync(fixture.loadNetwork))!;
      controller.networkData = network;
      final copy = AppCopy.forLanguage(AppLanguage.english);
      await tester.pumpWidget(
        MaterialApp(
          theme: ViberTheme.light(),
          home: Scaffold(
            body: AnimatedBuilder(
              animation: controller,
              builder: (context, _) =>
                  NetworkView(controller: controller, copy: copy),
            ),
          ),
        ),
      );
      Future<void> settle() async {
        await tester.runAsync(() async {
          for (
            var wait = 0;
            controller.nativeApprovalsLoading && wait < 2000;
            wait++
          ) {
            await Future<void>.delayed(const Duration(milliseconds: 1));
          }
        });
        await tester.pumpAndSettle();
        expect(controller.nativeApprovalsLoading, isFalse);
      }

      await settle();
      expect(controller.nativeApprovals, hasLength(2));
      expect(controller.nativePendingCount, 2);
      expect(controller.pendingApprovalCount, 2);
      expect(
        find.text('${network.approvals.length + 2}'),
        findsOneWidget,
        reason: 'the Waiting heading counts tool questions too',
      );
      for (final (key, label) in [
        ('managed_run:same-id', 'claude · Tool approvals: 1'),
        ('manual_capture:same-id', 'Manual app · Tool approvals: 1'),
      ]) {
        final header = find.byKey(Key('native-session-$key'));
        await tester.scrollUntilVisible(
          header,
          300,
          scrollable: find.byType(Scrollable).last,
        );
        expect(
          find.descendant(of: header, matching: find.text(label)),
          findsOneWidget,
        );
      }
      final manualID =
          (items.last['approval']! as Map<String, Object?>)['id']! as String;
      final deny = find.byKey(Key('native-approval-$manualID-deny'));
      await tester.scrollUntilVisible(
        deny,
        300,
        scrollable: find.byType(Scrollable).last,
      );
      await tester.ensureVisible(deny);
      await tester.pumpAndSettle();
      await tester.tap(deny);
      await tester.runAsync(() async {
        for (var wait = 0; posts.isEmpty && wait < 2000; wait++) {
          await Future<void>.delayed(const Duration(milliseconds: 1));
        }
      });
      expect(posts, hasLength(1), reason: controller.nativeApprovalError);
      expect(
        Uri.decodeComponent(posts.single.url.path),
        '/api/v1/captures/manual_capture:same-id/native-tools/approvals/$manualID/actions/decide',
      );
      await tester.runAsync(() async {
        await Future<void>.delayed(const Duration(milliseconds: 5));
        await controller.refreshNativeApprovals();
      });
      await settle();
      expect(controller.nativePendingCount, 1);
      expect(
        controller.nativeApprovals.single.captureKey,
        'managed_run:same-id',
      );
      expect(
        find.byKey(const Key('native-session-manual_capture:same-id')),
        findsNothing,
      );
      await tester.pumpWidget(const SizedBox());
    },
  );
}
